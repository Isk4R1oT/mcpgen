const I18nContext = React.createContext({ lang: 'en', t: (k) => k, setLang: () => {} });

function I18nProvider({ children }) {
  const [lang, setLang] = React.useState(() => {
    try { return localStorage.getItem('mcpgen-lang') || 'en'; } catch { return 'en'; }
  });
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const tr = React.useCallback((k) => dict[k] ?? TRANSLATIONS.en[k] ?? k, [dict]);
  const handleSetLang = React.useCallback((l) => {
    setLang(l);
    try { localStorage.setItem('mcpgen-lang', l); } catch {}
  }, []);
  return (
    <I18nContext.Provider value={{ lang, t: tr, setLang: handleSetLang }}>
      {children}
    </I18nContext.Provider>
  );
}

function useI18n() { return React.useContext(I18nContext); }

function LangSwitcher({ size = 'sm' }) {
  const { lang, setLang } = useI18n();
  const [open, setOpen] = React.useState(false);
  const cur = LANGUAGES.find(l => l.id === lang) || LANGUAGES[0];
  return (
    <div style={{ position: 'relative' }}>
      <button
        onClick={() => setOpen(o => !o)}
        className={`mc-btn mc-btn-ghost mc-btn-${size}`}
        style={{ fontFamily: 'var(--font-mono)', letterSpacing: '.04em', fontSize: 11.5, padding: '0 10px' }}
      >
        <span style={{ fontWeight: 600 }}>{cur.label}</span>
        <Icon name="caret-d" size={10} />
      </button>
      {open && (
        <>
          <div onClick={() => setOpen(false)} style={{ position: 'fixed', inset: 0, zIndex: 99 }} />
          <div style={{
            position: 'absolute', right: 0, top: 'calc(100% + 4px)', zIndex: 100,
            background: 'var(--card)', border: '1px solid var(--border-sharp)',
            borderRadius: 'var(--radius)', boxShadow: 'var(--shadow)',
            minWidth: 160, padding: 4,
          }}>
            {LANGUAGES.map(l => (
              <button
                key={l.id}
                onClick={() => { setLang(l.id); setOpen(false); }}
                style={{
                  display: 'flex', alignItems: 'center', justifyContent: 'space-between',
                  width: '100%', padding: '7px 10px', border: 0,
                  background: l.id === lang ? 'var(--ink)' : 'transparent',
                  color: l.id === lang ? 'var(--paper)' : 'var(--text)',
                  fontFamily: 'var(--font-mono)', fontSize: 12, cursor: 'pointer',
                  borderRadius: 'var(--radius)', textAlign: 'left',
                }}
              >
                <span>{l.name}</span>
                <span style={{ opacity: .6, fontSize: 10.5, letterSpacing: '.04em' }}>{l.label}</span>
              </button>
            ))}
          </div>
        </>
      )}
    </div>
  );
}

Object.assign(window, { LANGUAGES, TRANSLATIONS, I18nProvider, useI18n, LangSwitcher });
